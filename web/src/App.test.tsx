import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter, useLocation } from 'react-router-dom'
import { afterEach, describe, expect, it, vi } from 'vitest'
import App from './App'
import { clearSession, fixtureAdapter, fixtureData, getSessionToken } from './fixtures'

function LocationSearch() { return <output data-testid="location-search">{useLocation().search}</output> }
function renderApp(path = '/') { return render(<MemoryRouter initialEntries={[path]}><App /><LocationSearch /></MemoryRouter>) }

describe('operator demo shell', () => {
  afterEach(() => { clearSession(); fixtureAdapter.policyRevision = 1 })
  it.each([['/', 'Overview'], ['/connections', 'Connections'], ['/keys', 'Keys & Policies'], ['/usage', 'Usage'], ['/routing', 'Routing'], ['/settings', 'Settings & Diagnostics']])('renders %s and marks its navigation link', (path, title) => {
    renderApp(path)
    expect(screen.getByRole('heading', { name: title })).toBeInTheDocument()
    expect(within(screen.getByRole('navigation', { name: 'Primary navigation' })).getByRole('link', { name: new RegExp(title) })).toHaveAttribute('aria-current', 'page')
    expect(screen.getByText('DEMO DATA — NOT LIVE')).toHaveAttribute('role', 'status')
  })
  it('switches themes and supports keyboard tab traversal by accessible names', async () => {
    const user = userEvent.setup()
    renderApp()
    await user.click(screen.getByRole('link', { name: /Overview/ }))
    await user.tab()
    expect(screen.getByRole('link', { name: /Connections/ })).toHaveFocus()
    await user.tab()
    expect(screen.getByRole('link', { name: /Keys & Policies/ })).toHaveFocus()
    await user.tab()
    expect(screen.getByRole('link', { name: /Usage/ })).toHaveFocus()
    await user.tab()
    expect(screen.getByRole('link', { name: /Routing/ })).toHaveFocus()
    await user.tab()
    expect(screen.getByRole('link', { name: /Settings & Diagnostics/ })).toHaveFocus()
    const button = screen.getByRole('button', { name: 'Switch to dark theme' })
    await user.click(button)
    expect(document.querySelector('.theme-dark')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Switch to light theme' })).toBeInTheDocument()
  })
  it('renders selectable loading, error and conflict fixture states', async () => {
    const user = userEvent.setup()
    renderApp()
    const selector = screen.getByRole('combobox', { name: 'Simulate fixture state' })
    await user.selectOptions(selector, 'loading')
    expect(screen.getByText('Loading synthetic fixture data…')).toHaveAttribute('role', 'status')
    await user.selectOptions(selector, 'error')
    expect(screen.getByRole('alert')).toHaveTextContent('Choose Ready to retry')
    await user.selectOptions(selector, 'conflict')
    expect(screen.getByText(/Current fixture revision: 2/)).toHaveAttribute('role', 'status')
    await user.selectOptions(selector, 'ready')
    expect(screen.getByRole('heading', { name: 'Overview' })).toBeInTheDocument()
  })
  it('keeps nullable counters and tri-state capabilities, and clears demo token on logout', async () => {
    const user = userEvent.setup()
    renderApp('/usage')
    expect(screen.getAllByText('Unknown').length).toBeGreaterThan(0)
    expect(Object.values(fixtureData.connections[0].capabilities)).toContain('supported')
    expect(Object.values(fixtureData.connections[0].capabilities)).toContain('unsupported')
    expect(Object.values(fixtureData.connections[0].capabilities)).toContain('unknown')
    const ready = fixtureAdapter.read(fixtureData, 'ready')
    expect(ready.status).toBe('success')
    if (ready.status !== 'success') throw new Error('Expected fixture success')
    expect(ready.data.usage.some(record => record.outputTokens === null)).toBe(true)
    const tokenInput = screen.getByLabelText('Demo-only bearer token')
    await user.type(tokenInput, 'demo-secret')
    await user.click(screen.getByRole('button', { name: 'Start demo session' }))
    expect(getSessionToken()).toBe('demo-secret')
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
    expect(screen.queryByText('demo-secret')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Log out' }))
    expect(getSessionToken()).toBeNull()
    expect(screen.getByLabelText('Demo-only bearer token')).toHaveValue('')
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
  })
  it('creates and manages connections without retaining credential values, and displays tri-state badges', async () => {
    const user = userEvent.setup()
    renderApp('/connections')
    expect(screen.getByText('streaming: supported')).toBeInTheDocument()
    expect(screen.getByText('tools: unsupported')).toBeInTheDocument()
    expect(screen.getByText('reasoning: unknown')).toBeInTheDocument()
    await user.type(screen.getByLabelText('Account ID'), 'new-account')
    const credentialFields = screen.getAllByLabelText(/Credential/)
    await user.type(credentialFields[0], 'never-render-this')
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(screen.getAllByText('new-account').length).toBe(2)
    expect(screen.queryByText('never-render-this')).not.toBeInTheDocument()
    expect(screen.getAllByLabelText(/Credential/).every(field => (field as HTMLInputElement).value === '')).toBe(true)
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
    await user.type(screen.getByLabelText('Replace credential (write-only)'), 'replacement-secret')
    await user.click(screen.getByRole('button', { name: 'Replace credential' }))
    expect(screen.getByText('Updated just now')).toBeInTheDocument()
    expect(screen.queryByText('replacement-secret')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'OAuth' }))
    expect(screen.getByText('OAuth started')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Disable account' }))
    expect(screen.getByText('Disabled')).toBeInTheDocument()
  })
  it('shows a created key once, confirms named revocation, and preserves inputs on conflict', async () => {
    const user = userEvent.setup()
    renderApp('/keys')
    await user.type(screen.getByLabelText('Label'), 'one-time test')
    await user.click(screen.getByRole('button', { name: 'Create key' }))
    const dialog = screen.getByRole('dialog')
    const raw = within(dialog).getByText(/^pr_demo_/).textContent
    expect(raw).toBeTruthy()
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.length).toBe(0)
    await user.click(within(dialog).getByRole('button', { name: /dismiss/ }))
    expect(screen.queryByText(raw!)).not.toBeInTheDocument()
    await user.click(screen.getAllByRole('button', { name: 'Revoke' })[0])
    expect(screen.getByRole('heading', { name: 'Revoke Demo key?' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Confirm revoke Demo key' }))
    expect(screen.getByText('revoked')).toBeInTheDocument()
    await user.type(screen.getByLabelText('Label'), 'conflict')
    await user.click(screen.getByRole('button', { name: 'Simulate concurrent policy update' }))
    await user.click(screen.getByRole('button', { name: 'Create key' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Revision conflict')
    expect(screen.getByLabelText('Label')).toHaveValue('conflict')
    await user.click(screen.getByRole('button', { name: /Refresh revision/ }))
    expect(screen.getByLabelText('Label')).toHaveValue('conflict')
    await user.click(screen.getByRole('button', { name: 'Create key' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('conflict')
  })
  it('copies keys with feedback and handles unavailable clipboard', async () => {
    const user = userEvent.setup()
    renderApp('/keys')
    await user.type(screen.getByLabelText('Label'), 'copy test')
    await user.click(screen.getByRole('button', { name: 'Create key' }))
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
    await user.click(screen.getByRole('button', { name: 'Copy key' }))
    expect(writeText).toHaveBeenCalledWith(screen.getByText(/^pr_demo_/).textContent)
    expect(within(screen.getByRole('dialog')).getByRole('status')).toHaveTextContent('Key copied to clipboard')
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined })
    await user.click(screen.getByRole('button', { name: 'Copy key' }))
    expect(within(screen.getByRole('dialog')).getByRole('status')).toHaveTextContent('Select and copy the key manually')
  })
  it('moves modal focus, contains tab navigation, dismisses on Escape and restores the trigger', async () => {
    const user = userEvent.setup()
    renderApp('/keys')
    const trigger = screen.getAllByRole('button', { name: 'Revoke' })[0]
    trigger.focus()
    await user.click(trigger)
    const dialog = screen.getByRole('dialog')
    expect(dialog).toContainElement(document.activeElement as HTMLElement)
    const title = within(dialog).getByRole('heading', { name: 'Revoke Demo key?' })
    expect(title).toHaveFocus()
    await user.tab({ shift: true })
    expect(within(dialog).getByRole('button', { name: /Confirm revoke/ })).toHaveFocus()
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
  })
  it('shows overview null distinctly from zero and usage filters, pages and fallback details', async () => {
    const user = userEvent.setup()
    renderApp()
    expect(screen.getByText('Unknown')).toBeInTheDocument()
    expect(screen.getByText('Ready', { selector: 'strong' })).toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: /Usage/ }))
    await user.selectOptions(screen.getByLabelText('Rows per page'), '5')
    expect(screen.getByText('0', { selector: 'td' })).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Rows per page'), '2')
    await user.click(screen.getByRole('button', { name: 'Next' }))
    expect(screen.getByText(/Page 2 of/)).toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Filter by model'), 'example-model')
    expect(screen.getByText(/Page 1 of 1/)).toBeInTheDocument()
    expect(screen.getByLabelText('Filter by model')).toHaveValue('example-model')
    const recovered = screen.getByText('req-103').closest('tr')!
    await user.click(within(recovered).getByRole('button', { name: 'Show details' }))
    expect(screen.getByText(/confirmed safe-retry disposition/)).toBeInTheDocument()
    expect(within(recovered).getByText('success')).toBeInTheDocument()
    expect(screen.getByText(/Synthetic fixture timeout/)).toBeInTheDocument()
    expect(screen.getByLabelText('Filter by model')).toHaveValue('example-model')
    await user.selectOptions(screen.getByLabelText('Filter by model'), 'other-model')
    const ambiguous = screen.getByText('req-101').closest('tr')!
    await user.click(within(ambiguous).getByRole('button', { name: 'Show details' }))
    expect(screen.getByText('Not retried: delivery outcome ambiguous')).toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: /Connections/ }))
    await user.click(screen.getByRole('link', { name: /Usage/ }))
    expect(screen.getByLabelText('Filter by model')).toHaveValue('other-model')
  })
  it('renders read-only routes and safe diagnostics and logs out', async () => {
    const user = userEvent.setup()
    renderApp('/routing')
    expect(screen.getByText(/Changes require configuration and restart/)).toBeInTheDocument()
    expect(screen.getByText('reasoning: unknown')).toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: /Settings/ }))
    expect(screen.getByText('demo-correlation-104')).toBeInTheDocument()
    expect(screen.getByText(/Restart required/)).toBeInTheDocument()
    const writeText = vi.fn().mockResolvedValue(undefined)
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
    await user.click(screen.getByRole('button', { name: 'Copy correlation ID' }))
    expect(writeText).toHaveBeenCalledWith('demo-correlation-104')
    await user.type(screen.getByLabelText('Demo-only bearer token'), 'secret-token')
    await user.click(screen.getByRole('button', { name: 'Start demo session' }))
    await user.click(screen.getByRole('button', { name: /Log out and clear cached views/ }))
    expect(getSessionToken()).toBeNull()
    expect(screen.queryByText('secret-token')).not.toBeInTheDocument()
  })
  it('clears credential form and one-time secret dialog on logout', async () => {
    const user = userEvent.setup()
    renderApp('/keys')
    await user.type(screen.getByLabelText('Demo-only bearer token'), 'operator-token')
    await user.click(screen.getByRole('button', { name: 'Start demo session' }))
    await user.type(screen.getByLabelText('Label'), 'transient-key')
    await user.click(screen.getByRole('button', { name: 'Create key' }))
    expect(screen.getByRole('dialog')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Log out' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByLabelText('Label')).toHaveValue('')
    expect(getSessionToken()).toBeNull()
    await user.click(screen.getByRole('link', { name: /Connections/ }))
    await user.type(screen.getByLabelText('Demo-only bearer token'), 'operator-again')
    await user.click(screen.getByRole('button', { name: 'Start demo session' }))
    await user.type(screen.getByLabelText('Replace credential (write-only)'), 'credential-buffer')
    await user.click(screen.getByRole('button', { name: 'Log out' }))
    expect(screen.getByLabelText('Replace credential (write-only)')).toHaveValue('')
    expect(screen.queryByText('credential-buffer')).not.toBeInTheDocument()
  })
  it('filters by account and time, restores query filters, handles empty results and malformed paging', async () => {
    renderApp('/usage?model=example-model&account=example&from=2026-10-17&to=2026-10-17&page=999&size=bogus')
    expect(screen.getByLabelText('Filter by model')).toHaveValue('example-model')
    expect(screen.getByLabelText('Filter by account')).toHaveValue('example')
    expect(screen.getByLabelText('Rows per page')).toHaveValue('2')
    expect(screen.getByText(/Page 1 of 1/)).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Time to'), { target: { value: '2026-10-18' } })
    fireEvent.change(screen.getByLabelText('Time from'), { target: { value: '2026-10-18' } })
    expect(screen.getByText(/No requests match active filters/)).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('Time from'), { target: { value: '2026-10-17' } })
    expect(screen.getByLabelText('Filter by model')).toHaveValue('example-model')
    await userEvent.setup().selectOptions(screen.getByLabelText('Filter by account'), 'example-fallback')
    expect(screen.getByText('req-103')).toBeInTheDocument()
    expect(screen.queryByText('req-104')).not.toBeInTheDocument()
    expect(screen.getByText('example-fallback', { selector: 'td' })).toBeInTheDocument()
  })
  it.each([
    ['model', 'removed-model', 'Filter by model'],
    ['account', 'removed-account', 'Filter by account'],
    ['status', 'removed-outcome', 'Filter by outcome'],
  ])('normalizes stale %s query filters to All', async (key, value, label) => {
    renderApp(`/usage?${key}=${value}`)
    expect(screen.getByLabelText(label)).toHaveValue('')
    expect(screen.getByText('req-104')).toBeInTheDocument()
    await waitFor(() => expect(screen.getByTestId('location-search')).not.toHaveTextContent(key))
    expect(screen.getByText(/Page 1 of 2/)).toBeInTheDocument()
  })
  it('shows recent failures from overview, clears malformed dates, and flags reversed dates', async () => {
    const user = userEvent.setup()
    const { unmount } = renderApp('/')
    const failedActivity = screen.getByRole('link', { name: /req-101 · error/ })
    expect(failedActivity).toHaveAttribute('href', '/usage?model=other-model&status=error')
    await user.click(failedActivity)
    expect(screen.getByText('req-101')).toBeInTheDocument()
    unmount()
    const malformed = renderApp('/usage?from=bad&to=2026-02-30')
    expect(screen.getByLabelText('Time from')).toHaveValue('')
    expect(screen.getByLabelText('Time to')).toHaveValue('')
    expect(screen.getByText('req-104')).toBeInTheDocument()
    malformed.unmount()
    renderApp('/usage?from=2026-10-18&to=2026-10-17')
    expect(screen.getByLabelText('Time from')).toHaveValue('2026-10-18')
    expect(screen.getByLabelText('Time to')).toHaveValue('2026-10-17')
    expect(screen.getByRole('alert')).toHaveTextContent(/start date must be on or before the end date/i)
    expect(screen.queryByText('req-104')).not.toBeInTheDocument()
  })
  it('keeps a reversed date range visible and empty until the operator corrects its end', async () => {
    const user = userEvent.setup()
    renderApp('/usage?from=2026-10-17&to=2026-10-17')
    await user.clear(screen.getByLabelText('Time from'))
    await user.type(screen.getByLabelText('Time from'), '2026-10-18')
    expect(screen.getByLabelText('Time from')).toHaveValue('2026-10-18')
    expect(screen.getByLabelText('Time to')).toHaveValue('2026-10-17')
    expect(screen.getByRole('alert')).toHaveTextContent(/start date must be on or before the end date/i)
    expect(screen.queryByText('req-104')).not.toBeInTheDocument()
    await user.clear(screen.getByLabelText('Time to'))
    await user.type(screen.getByLabelText('Time to'), '2026-10-18')
    expect(screen.getByLabelText('Time from')).toHaveValue('2026-10-18')
    expect(screen.getByLabelText('Time to')).toHaveValue('2026-10-18')
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(screen.getByText(/No requests match active filters/)).toBeInTheDocument()
  })
  it('renders all routing capability states and an accurate zero account count', () => {
    const prior = fixtureData.overview.enabledAccounts
    fixtureData.overview.enabledAccounts = 0
    const { unmount } = renderApp('/routing')
    expect(screen.getByText('streaming: supported')).toBeInTheDocument()
    expect(screen.getByText('tools: unsupported')).toBeInTheDocument()
    expect(screen.getByText('reasoning: unknown')).toBeInTheDocument()
    unmount()
    const overview = renderApp('/')
    expect(screen.getByText('0', { selector: 'strong' })).toBeInTheDocument()
    overview.unmount()
    fixtureData.overview.enabledAccounts = prior
    renderApp('/')
    expect(screen.getByText('1', { selector: 'strong' })).toBeInTheDocument()
    expect(fixtureData.overview.enabledAccounts).toBe(fixtureData.connections.filter(account => account.enabled).length)
  })
})
